def gen_exact_corpus(count=200):
    """Determinant signs computed exactly with rational arithmetic."""
    rng = random.Random(SEED + 4)
    rows = []

    def perturbed(base, scale):
        return base * (1.0 + rng.uniform(-1.0, 1.0) * scale)

    for index in range(count):
        style = index % 4
        if style == 0:
            rows_xyz = [
                [rng.uniform(-1, 1) for _ in range(3)] for _ in range(3)
            ]
        elif style == 1:
            # Nearly collinear: two rows almost proportional to the first.
            base = [rng.uniform(-1, 1) for _ in range(3)]
            rows_xyz = [
                base,
                [perturbed(v, 1e-15) for v in base],
                [perturbed(v, 1e-15) for v in base],
            ]
        elif style == 2:
            # Exactly proportional rows: the determinant is exactly zero.
            base = [rng.uniform(-1, 1) for _ in range(3)]
            rows_xyz = [base, [2.0 * v for v in base], [rng.uniform(-1, 1) for _ in range(3)]]
        else:
            # Coordinates that differ only in their last bits.
            base = [rng.uniform(0.5, 1.0) for _ in range(3)]
            rows_xyz = [
                base,
                [math.nextafter(v, 2.0) for v in base],
                [math.nextafter(v, 0.0) for v in base],
            ]
            rows_xyz[2][rng.randint(0, 2)] = math.nextafter(base[0], 2.0)

        a, b, c = rows_xyz
        det = (
            Fraction(a[0]) * (Fraction(b[1]) * Fraction(c[2]) - Fraction(b[2]) * Fraction(c[1]))
            - Fraction(a[1]) * (Fraction(b[0]) * Fraction(c[2]) - Fraction(b[2]) * Fraction(c[0]))
            + Fraction(a[2]) * (Fraction(b[0]) * Fraction(c[1]) - Fraction(b[1]) * Fraction(c[0]))
        )
        sign = (det > 0) - (det < 0)
        det2 = Fraction(a[0]) * Fraction(b[1]) - Fraction(a[1]) * Fraction(b[0])
        sign2 = (det2 > 0) - (det2 < 0)
        rows.append(
            "\t\t{{\n"
            "\t\t\ta: ({a}),\n"
            "\t\t\tb: ({b}),\n"
            "\t\t\tc: ({c}),\n"
            "\t\t\tdet3_sign: {sign},\n"
            "\t\t\tdet2_sign: {sign2},\n"
            "\t\t}},".format(
                a=", ".join(f(v) for v in a),
                b=", ".join(f(v) for v in b),
                c=", ".join(f(v) for v in c),
                sign=sign,
                sign2=sign2,
            )
        )
    body = HEADER.format(
        title="Determinant signs computed with exact rational arithmetic.",
        name="ExactCorpus",
    )
    body += """
\t## Three rows of doubles, the exact sign of their 3x3 determinant, and the
\t## exact sign of the 2x2 minor `a0 * b1 - a1 * b0`.
\t##
\t## Both signs come from Python's `fractions.Fraction`, so they are the
\t## mathematically exact answers rather than another implementation's.
\tCase := {
\t\ta : (F64, F64, F64),
\t\tb : (F64, F64, F64),
\t\tc : (F64, F64, F64),
\t\tdet3_sign : I8,
\t\tdet2_sign : I8,
\t}

\tcases : List(Case)
\tcases = [
"""
    body += "\n".join(rows)
    body += "\n\t]\n}\n"
    write("ExactCorpus.roc", body)


