def f(x):
    """A float literal Roc parses back to the same double."""
    return repr(float(x))


def rand_xyz(rng):
    """A random unit vector, as a tuple of three floats."""
    while True:
        x = rng.uniform(-1, 1)
        y = rng.uniform(-1, 1)
        z = rng.uniform(-1, 1)
        n = math.sqrt(x * x + y * y + z * z)
        if 1e-6 < n <= 1.0:
            return (x / n, y / n, z / n)


def rand_point(rng):
    return s2.Point(*rand_xyz(rng))


def write(name, text):
    path = os.path.join(OUT_DIR, name)
    with open(path, "w") as handle:
        handle.write(text)
    print("wrote %s (%d bytes)" % (path, len(text)))


