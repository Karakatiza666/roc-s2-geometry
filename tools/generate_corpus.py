    def random_ids(n):
        ids = []
        for _ in range(n):
            level = rng.randint(0, 12)
            ids.append(s2.CellId.from_point(rand_point(rng)).parent(level))
        return ids

    for _ in range(count):
        raw_a = random_ids(rng.randint(1, 6))
        raw_b = random_ids(rng.randint(1, 6))
        a = s2.CellUnion(raw_a)
        b = s2.CellUnion(raw_b)
        union = s2.CellUnion.get_union(a, b)
        inter = s2.CellUnion.get_intersection(a, b)
        diff = s2.CellUnion.get_difference(a, b)
