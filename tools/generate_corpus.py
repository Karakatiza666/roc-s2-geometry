"""Generate this package's golden test corpora.

Most expected values come from s2sphere, an independent Python port of the
same C++ library, so the corpora cross-check this port against a third
implementation rather than against itself. The exact-arithmetic corpus is
computed with Python's `fractions.Fraction` instead, which is exact by
construction. The cover corpus comes from upstream's own C++ S2RegionCoverer,
through tools/cover_oracle.cc: s2sphere ports an older version of that
algorithm, whose coverings are different.

Usage:

    pip install s2sphere
    python3 tools/generate_corpus.py --cover-oracle path/to/cover_oracle

Without --cover-oracle the cover corpus is skipped. With --only cover, only
the cover corpus is written, and s2sphere is not needed.

Writes the `*Corpus.roc` files in `tests/`. Regenerate only when the corpus
needs to grow or change shape; the committed output is what the tests read.
"""

