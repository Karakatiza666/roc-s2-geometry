"""Generate the polygon relation corpus from upstream's own test suite.

`s2polygon_test.cc` builds thirty-odd polygons out of a set of named loops:
nested rings around a point, rings around the poles, shapes with holes, and
pairs of rectangles arranged to touch without crossing. It then states, for
every interesting pair, whether A contains B, B contains A, and whether the two
intersect. That table is the reference answer for the polygon predicates.

This script parses the loop definitions, the polygons built from them and the
relation table out of that file and emits them as Roc data. The Roc side
(`tests/S2PolygonTest.roc`) is what checks the port against them.

Usage:

    curl -sSLO https://raw.githubusercontent.com/google/s2geometry/v0.11.1/src/s2/s2polygon_test.cc
    python3 tools/generate_polygon_corpus.py s2polygon_test.cc
    roc fmt .
"""

import re
import sys
from pathlib import Path

FULL = "FULL"


def parse_constants(text):
    """The `constexpr string_view kX = "...";` loop definitions."""
    out = {}
    for match in re.finditer(
        r"constexpr string_view (k\w+) =\s*((?:\s*\"[^\"]*\")+)\s*;", text
    ):
        out[match.group(1)] = "".join(re.findall(r"\"([^\"]*)\"", match.group(2)))
    return out


def loops_of(spec, constants):
    """A polygon spec as a list of loops, each a list of (lat, lng)."""
    if spec == FULL:
        return FULL
    text = "".join(constants[name] for name in spec)
    loops = []
    for part in text.split(";"):
        part = part.strip()
        if not part:
            continue
        points = []
        for point in part.split(","):
            lat, lng = point.strip().split(":")
            points.append((float(lat), float(lng)))
        loops.append(points)
    return loops


def parse_polygons(text, constants):
    """The fixture's named polygons, as {name: [loop, ...]} or FULL."""
    start = text.index("S2PolygonTestBase::S2PolygonTestBase()")
    body = text[start : text.index("static void CheckEqual", start)]
    polygons = {"empty_": []}
    for match in re.finditer(r"(\w+_)\(\s*MakePolygon\(([^;]*?)\)\),?", body):
        name, argument = match.group(1), match.group(2)
        if '"full"' in argument:
            polygons[name] = FULL
            continue
        names = re.findall(r"\bk\w+", argument)
        polygons[name] = loops_of(names, constants)
    return polygons


def parse_relations(text, polygons):
    """The relation table, as [(a, b, contains, contained, intersects)]."""
    start = text.index("TEST_F(S2PolygonTestBase, Relations)")
    body = text[start : text.index("#undef TestRelation", start)]
    rows = []
    for match in re.finditer(
        r"TestRelation\(\s*\*(\w+_),\s*\*(\w+_),\s*"
        r"(true|false),\s*(true|false),\s*(true|false)\)",
        body,
    ):
        a, b, contains, contained, intersects = match.groups()
        rows.append(
            (
                polygons[a],
                polygons[b],
                contains == "true",
                contained == "true",
                intersects == "true",
            )
        )
    return rows


def parse_contains(text, constants):
    """The `CheckContains(kA, kB)` pairs, where A contains B."""
    return [
        (loops_of([match.group(1)], constants), loops_of([match.group(2)], constants))
        for match in re.finditer(r"CheckContains\((k\w+), (k\w+)\)", text)
    ]


def parse_contains_point(text, constants):
    """The `CheckContainsPoint(kA, kPoint)` pairs."""
    out = []
    for match in re.finditer(r"CheckContainsPoint\((k\w+), (k\w+)\)", text):
        lat, lng = constants[match.group(2)].split(":")
        out.append((loops_of([match.group(1)], constants), float(lat), float(lng)))
    return out


def render_loops(loops):
    if loops == FULL:
        return "Bool.True", "[]"
    rendered = []
    for points in loops:
        rendered.append(
            "[" + ", ".join(f"({lat!r}, {lng!r})" for lat, lng in points) + "]"
        )
    return "Bool.False", "[" + ", ".join(rendered) + "]"


HEADER = '''## Polygon pairs and the relations that hold between them.
##
## Generated by `tools/generate_polygon_corpus.py` from the fixture and the
## relation table in upstream's `s2polygon_test.cc`. Do not edit by hand.
##
## A polygon is a list of loops, each a list of lat/lng positions in degrees,
## nested so that a point inside an odd number of them is inside the polygon.
## The empty polygon is the empty list; `is_full` marks the whole sphere.
##
## Internal to this package.
PolygonCorpus := [].{

\tCase := {
\t\ta : List(List((F64, F64))),
\t\ta_full : Bool,
\t\tb : List(List((F64, F64))),
\t\tb_full : Bool,
\t\tcontains : Bool,
\t\tcontained : Bool,
\t\tintersects : Bool,
\t}

\t## One loop containing another, from upstream's nesting checks.
\tPair : (List(List((F64, F64))), List(List((F64, F64))))

\t## A polygon and a position it contains.
\tPointCase : (List(List((F64, F64))), F64, F64)
'''


def main():
    source = Path(
        sys.argv[1] if len(sys.argv) > 1 else "s2polygon_test.cc"
    ).read_text()
    constants = parse_constants(source)
    polygons = parse_polygons(source, constants)
    relations = parse_relations(source, polygons)
    contains = parse_contains(source, constants)
    points = parse_contains_point(source, constants)

    out = [HEADER, "\tcases : List(Case)", "\tcases = ["]
    for a, b, holds, held, meets in relations:
        a_full, a_loops = render_loops(a)
        b_full, b_loops = render_loops(b)
        out.append(
            f"\t\t{{\n"
            f"\t\t\ta: {a_loops},\n"
            f"\t\t\ta_full: {a_full},\n"
            f"\t\t\tb: {b_loops},\n"
            f"\t\t\tb_full: {b_full},\n"
            f"\t\t\tcontains: {'Bool.True' if holds else 'Bool.False'},\n"
            f"\t\t\tcontained: {'Bool.True' if held else 'Bool.False'},\n"
            f"\t\t\tintersects: {'Bool.True' if meets else 'Bool.False'},\n"
            f"\t\t}},"
        )
    out.append("\t]\n")

    out.append("\t## Pairs where the first polygon contains the second.")
    out.append("\tnested : List(Pair)")
    out.append("\tnested = [")
    for a, b in contains:
        out.append(f"\t\t({render_loops(a)[1]}, {render_loops(b)[1]}),")
    out.append("\t]\n")

    out.append("\t## Polygons and positions they contain.")
    out.append("\tpoints : List(PointCase)")
    out.append("\tpoints = [")
    for loops, lat, lng in points:
        out.append(f"\t\t({render_loops(loops)[1]}, {lat!r}, {lng!r}),")
    out.append("\t]\n}")

    Path("tests/PolygonCorpus.roc").write_text("\n".join(out) + "\n")
    print(
        f"{len(polygons)} polygons, {len(relations)} relations, "
        f"{len(contains)} nested pairs, {len(points)} points"
    )


if __name__ == "__main__":
    main()
