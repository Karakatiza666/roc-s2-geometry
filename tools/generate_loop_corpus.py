"""Generate the loop relation corpus from upstream's own test suite.

`s2loop_test.cc` defines two dozen named loops and then states, for every
interesting pair of them, which of four relations holds: A contains B, B
contains A, the two are disjoint, and together they cover the sphere. That
table is the reference answer for the containment predicates, degenerate cases
included: loops that share an edge, loops that share only a vertex, hemispheres
whose common boundary is the whole equator.

This script parses the fixture and the table out of that file and emits them as
Roc data. The assertions themselves are not copied: `tests/S2LoopRelationTest.roc`
re-derives what each flag implies, the way upstream's `TestRelationWithDesc`
does, and checks all of it against this port.

Usage:

    curl -sSLO https://raw.githubusercontent.com/google/s2geometry/v0.11.1/src/s2/s2loop_test.cc
    python3 tools/generate_loop_corpus.py s2loop_test.cc
    roc fmt .
"""

import re
import sys
from pathlib import Path

FLAGS = {"CONTAINS": 1, "CONTAINED": 2, "DISJOINT": 4, "COVERS": 8}


def parse_loops(text):
    """The fixture's named loops, as {name: "lat:lng, lat:lng, ..."}."""
    # Each is `name_(AddLoop("...")),` with the string possibly split across
    # lines by the C++ compiler's adjacent-literal concatenation.
    start = text.index("S2LoopTestBase()")
    end = text.index("snapped_loop_a_vertices")
    body = text[start:end]
    loops = {}
    for match in re.finditer(r"(\w+)_\(AddLoop\(((?:\s*\"[^\"]*\")+)\)\)", body):
        name = match.group(1)
        parts = re.findall(r"\"([^\"]*)\"", match.group(2))
        loops[name] = "".join(parts)
    loops["empty"] = "EMPTY"
    loops["full"] = "FULL"
    return loops


def parse_relations(text):
    """The relation table, as [(a, b, flags, shared_edge)]."""
    rows = []
    for match in re.finditer(
        r"TestRelation\(\s*(\w+)_,\s*(\w+)_,\s*([\w|\s]+?),\s*(true|false)\)", text
    ):
        a, b, flags, shared = match.groups()
        value = 0
        for flag in flags.split("|"):
            flag = flag.strip()
            if flag != "0":
                value |= FLAGS[flag]
        rows.append((a, b, value, shared == "true"))
    return rows


def vertices(spec):
    """A loop spec as Roc source: a kind tag and a list of lat/lng degrees."""
    if spec == "EMPTY":
        return "1", "[]"
    if spec == "FULL":
        return "2", "[]"
    points = []
    for point in spec.split(","):
        lat, lng = point.strip().split(":")
        points.append(f"({float(lat)!r}, {float(lng)!r})")
    return "0", "[" + ", ".join(points) + "]"


def main():
    source = Path(sys.argv[1] if len(sys.argv) > 1 else "s2loop_test.cc").read_text()
    loops = parse_loops(source)
    rows = parse_relations(source)

    header = """## Loop pairs and the relation that holds between them.
##
## Generated by `tools/generate_loop_corpus.py` from the fixture and the
## relation table in upstream's `s2loop_test.cc`. Do not edit by hand.
##
## `kind` is 0 for a loop through the listed positions, 1 for the empty loop
## and 2 for the full loop. `flags` is a bit set: 1 A contains B, 2 B contains
## A, 4 disjoint, 8 their union covers the sphere. `shared_edge` says the two
## loops have an edge in common, possibly reversed.
##
## Internal to this package.
LoopRelationCorpus := [].{

\tCase := {
\t\ta_kind : U8,
\t\ta : List((F64, F64)),
\t\tb_kind : U8,
\t\tb : List((F64, F64)),
\t\tflags : U8,
\t\tshared_edge : Bool,
\t}

\tcases : List(Case)
\tcases = ["""
    out = [header]

    for a, b, flags, shared in rows:
        a_kind, a_points = vertices(loops[a])
        b_kind, b_points = vertices(loops[b])
        out.append(
            f"\t\t# {a} / {b}\n"
            f"\t\t{{\n"
            f"\t\t\ta_kind: {a_kind},\n"
            f"\t\t\ta: {a_points},\n"
            f"\t\t\tb_kind: {b_kind},\n"
            f"\t\t\tb: {b_points},\n"
            f"\t\t\tflags: {flags},\n"
            f"\t\t\tshared_edge: {'Bool.True' if shared else 'Bool.False'},\n"
            f"\t\t}},"
        )
    out.append("\t]\n}")

    Path("tests/LoopRelationCorpus.roc").write_text("\n".join(out) + "\n")
    print(f"{len(loops)} loops, {len(rows)} relations")


if __name__ == "__main__":
    main()
